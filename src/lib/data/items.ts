/**
 * ХВАТ — как предмет ложится в руки. Свойство ПРЕДМЕТА, а не слота: слот
 * говорит, куда вещь надевается, хват — можно ли её туда надеть вообще.
 *
 *   'one'    — одноручное: идёт в любую руку;
 *   'two'    — двуручное: занимает обе, вторая рука остаётся пустой;
 *   'shield' — щит: только вторая рука, и это не оружие.
 *
 * Три значения взаимоисключающие, поэтому одно поле, а не два флага: щит,
 * который «одновременно и оружие», выразить нечем.
 */
export type Grip = 'one' | 'two' | 'shield'

/** Хваты, которые бывают у оружия. Щит оружием не бывает. */
export type WeaponGrip = Extract<Grip, 'one' | 'two'>

export interface WeaponTemplate {
  id: string
  noun: string // существительное для имени: «Щербатый Змеезуб»
  /** Хват оружия. Двуручное занимает обе руки и оставляет левую пустой. */
  grip: WeaponGrip
  weaponSpeed: Decimal // секунд между ударами (меньше = быстрее)
  damageMin: Decimal
  damageMax: Decimal
  // Побочные статы оружия — ОБЫЧНЫЕ модификаторы (не base).
  extra: Array<Omit<StatModifier, 'source'>>
}

/**
 * Щит. Не оружие: урона не даёт вовсе, зато даёт блок и запас HP.
 * Живёт в той же левой руке, что и второе одноручное, — выбирать между ними
 * и есть решение о стиле боя.
 */
export interface ShieldTemplate {
  id: string
  noun: string
  /** Всегда 'shield'. Поле есть в данных, а не подставляется кодом: хват
   *  читается из шаблона, и проверка контента сверяет его с типом. */
  grip: Extract<Grip, 'shield'>
  blockChance: Decimal // вероятность блока, доля
  blockValue: Decimal // сколько урона снимает удачный блок
  extra: Array<Omit<StatModifier, 'source'>>
}

// Побочные статы оружия и щитов — АТРИБУТЫ, а не готовые статы: «Змеезуб —
// оружие ловкости» читается из данных, а во что ловкость разворачивается,
// решает конвейер (data/balance.ts). Атрибуты растут с уровнем предмета,
// как и всё остальное на нём.
//
// И ТОЛЬКО ПЛОСКИЕ. Процентов на выпадающих и кованых вещах нет вовсе, и
// это правило, а не совпадение: процент считается от суммы конвейера, то
// есть от ОСТАЛЬНОЙ экипировки. Такой предмет нельзя сравнить сам по себе —
// его ценность зависит от того, что надето в других слотах, — и он не
// растёт ни от уровня вещи, ни от тира: множитель `power` в `loot.ts`
// умножает плоские прибавки, а проценту умножать нечего. Крушитель с
// «+10% силы» это и показывал: на первом уровне, когда силы нет вовсе,
// прибавка была РОВНО НУЛЁМ. Проценты остались там, где они и осмысленны, —
// в зачарованиях (`data/enchants.ts`), талантах и зельях: они множат
// растущий флэт, поэтому позднее зачарование само по себе сильнее раннего.
// Держится проверкой контента.
//
// Оружие трёх стилей. Числа подобраны так, чтобы равны были не ОРУЖИЯ, а
// СВЯЗКИ — то, что герой реально носит:
//
//   два одноручных: 7.5 + 7.5 * OFFHAND_PENALTY = 11.25 урона оружия в секунду;
//   двуручное:      11.25 — столько же, потому что занимает обе руки;
//   одноручное+щит: 7.5 — на треть меньше, и это ПЛАТА за блок и запас HP.
//
// Одноручные держат прежнее отношение (средний урон / weaponSpeed) = 7.5,
// двуручное — 11.25. Диапазон задан как min = ratio/1.5 * speed,
