// ЧТО ЗНАЧИТ «ЛУЧШЕ»: две оси и приоритет игрока.
//
// До этой правки мера была одна — убийств в секунду, — и она честно
// описывала только половину игры. Живучесть входит в неё ТОЛЬКО через
// аптайм, а в зоне, где герой не гибнет, аптайм равен единице: панцирь
// не двигает оценку вовсе, двуручное всегда «лучше» связки со щитом, и
// защитные ветки талантов отстают в полтора раза. Это третье появление
// одной и той же слепой зоны, и здесь она закрывается там, где её видит
// игрок.
//
// ОСЕЙ РОВНО ДВЕ, И ОБЕ СЧИТАЮТСЯ ПРОТИВ ЭТАЛОННОГО ПРОТИВНИКА — моба
// уровня героя, построенного той же `buildMonster` и не принадлежащего ни
// одной зоне (`REFERENCE_ARCHETYPE` в data/monsters.ts):
//
//   'damage'   — урон в секунду по эталону, с учётом ПЕРЕБОЯ добивающего
//                удара. Считает его та же `estimateCombatRate`, но берётся
//                чистая пропускная способность урона — без аптайма,
//                привалов и смертей;
//   'survival' — ЖИВУЧЕСТЬ: сколько урона герой держит за одну типичную
//                схватку, `(запас + реген × TYPICAL_FIGHT_SEC) / (1 −
//                смягчение)`. Число абсолютное, в единицах здоровья, и
//                больше — лучше, как у урона.
//
// ГРАНИЦА, КОТОРУЮ НЕЛЬЗЯ РАЗМЫВАТЬ: эти две оси — для ИГРОКА и для решений
// об экипировке. `estimateCombatRate` целиком и контракт цены боя — МОДЕЛЬ:
// по ним считаются прогноз зоны, оффлайн, прогон баланса и тесты. Оси обязаны
// быть простыми, устойчивыми и не зависеть от того, где герой стоит; модель
// обязана быть точной. Смешаешь — и одна и та же вещь начнёт читаться
// по-разному в двух шагах пути.

/** Ось, по которой предмет бывает лучше или хуже. */
export type UpgradeAxis = 'damage' | 'survival'

export const UPGRADE_AXES: readonly UpgradeAxis[] = ['damage', 'survival']

/**
 * ПРИОРИТЕТ ИГРОКА — переключатель на три положения в панели сумки. Это
 * настройка, а не свойство героя: она лежит в сейве и ничего не считает
 * сама, только выбирает, ПО КАКИМ осям смотреть.
 */
export type UpgradePriority = 'damage' | 'survival' | 'balance'

export const UPGRADE_PRIORITIES: readonly UpgradePriority[] = ['damage', 'survival', 'balance']

/**
 * ПО УМОЛЧАНИЮ — БАЛАНС. Игрок, который не трогал переключатель, не должен
 * терять ни защитные находки, ни атакующие: обе оси считаются, и предмет
 * лучше хотя бы по одной уже не «лишний».
 */
export const DEFAULT_UPGRADE_PRIORITY: UpgradePriority = 'balance'

/**
 * КАКИЕ ОСИ СМОТРИТ КАЖДОЕ ПОЛОЖЕНИЕ — данными, а не веткой в логике.
 *
 * Правило одно на все три: предмет — АПГРЕЙД, если он лучше хотя бы по
 * одной из перечисленных осей, и «ЛИШНИЙ», если не лучше ни по одной.
 * Отсюда сами собой получаются три обещания переключателя:
 *
 *   урон       — лишнее, если хуже по урону;
 *   выживание  — лишнее, если хуже по выживанию;
 *   баланс     — лишнее, ТОЛЬКО если хуже по ОБЕИМ осям.
 *
 * Ветки `if (приоритет === 'balance')` в логике нет и быть не должно:
 * появится четвёртое положение — оно добавится сюда строкой.
 */
export const UPGRADE_RULES: Record<UpgradePriority, { axes: readonly UpgradeAxis[] }> = {
  damage: { axes: ['damage'] },
  survival: { axes: ['survival'] },
  balance: { axes: UPGRADE_AXES },
}
