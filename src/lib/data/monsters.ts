// Скидка HP мобам ранних полос: герой приходит в них НЕДОСОБРАННЫМ.
//
// Недособран он дважды. Кнопки открываются уровнями (unlockLevel умений —
// 1/4/8), и пока набор неполон, урон в секунду ниже полного. А ВЕЩЕЙ у него
// на первой полосе нет вовсе: игра выдаёт одно белое оружие, остальные шесть
// слотов пусты, и закрывает их сам игрок находками. «Прямая против прямой»
// держит темп при ПОСТОЯННОМ наборе кнопок и полном комплекте — значит на
// полосах, где ни того, ни другого ещё нет, мобы обязаны быть тоньше ровно
// на долю недостающего урона.
//
// ОТКУДА 0.41 НА ПЕРВОЙ ПОЛОСЕ. Замер: герой в одном белом оружии клал моба
// стартовой зоны за 28 секунд при потолке коридора в 15, а стартовая зона
// переставала быть безопасной — новобранец умирал в обучающей зоне. Прежние
// 0.82 считались от героя в ПОЛНОМ РЕДКОМ комплекте, который игра дарила на
// первой секунде; комплекта больше нет, и число пересчитано под настоящего
// новобранца. Вторая полоса не тронута: на неё герой приходит уже одетым.
//
// Границы — полосы зон (1-5 и 6-10), а не уровни героя: скидка лежит на
// мобе, а дерётся с ним тот, кому он по лестнице и предназначен.
// ДВА ЧИСЛА НА ПОЛОСУ, а не одно, и это следствие пустых слотов. Недостающие
// кнопки бьют по УРОНУ героя — их лечит скидка hp. Недостающая (или, наоборот,
// непропорционально сильная) броня бьёт по ВХОДЯЩЕМУ — а его скидкой hp не
// поправить ничем: сколько моба ни утончай, бьёт он всё так же больно.
// Поэтому у ранних полос свой множитель и на урон.
//
// ПОСЛЕ ПОЯВЛЕНИЯ БРОНИ ЭТО УЖЕ НЕ ТОЛЬКО СКИДКА. Полоса 1-5 остаётся
// скидкой (у новобранца брони нет вовсе), а полоса 6-10 стала НАДБАВКОЙ:
// снижение бронёй считается по формуле `броня / (броня + K × уровень героя)`,
// у неё в знаменателе уровень героя, а в числителе — броня вещей, и вещь
// уровня L несёт не L, а `0.84 + 0.16 L` доли ставки. На шестом уровне
// знаменатель мал, и эталонный герой снижает 66.7% вместо асимптотических
// 48%. Полоса 6-10 возвращает цену её схватки в коридор.
export const EARLY_HP_DISCOUNT: ReadonlyArray<{
  belowLevel: number
  mult: Decimal
  damageMult: Decimal
}> = [
  // Мобы 1-5: у героя одна кнопка и ОДНО белое оружие при шести пустых слотах.
  // Это ещё и БЕЗОПАСНАЯ зона — та, куда возвращает смерть; убивать в ней
  // нельзя по определению, а голому новобранцу она это делала.
  //
  // 0.0841 на урон — это НЕ «поблажка новичку», а тот же контракт цены боя,
  // пересчитанный на героя, у которого нет ни брони, ни щита, ни второй
  // кнопки. При общей ставке моб первой полосы снимал бы с него сто с лишним
  // процентов здоровья за бой, то есть убивал бы в безопасной зоне.
  //
  // ЧИСЛО ПРИВЯЗАНО К ПРОИЗВЕДЕНИЮ, А НЕ К СЕБЕ: у героя первой полосы брони
  // НЕТ, поэтому подъём общей ставки под броню его не касается, и полоса
  // обязана его отыграть обратно. 38.87 × 0.0841 = 3.269 — ровно то же
  // произведение, что и до брони (18.36 × 0.178). Стартовая зона не сдвинулась
  // ни на сотую: 19.1% валовой цены боя и там, и там.
  { belowLevel: 6, mult: new Decimal(0.41), damageMult: new Decimal(0.0841) },
  // Мобы 6-10: две кнопки, комплект уже собирается — и броня на нём режет
  // больше, чем на любой другой полосе (66.7% против 48-54% дальше). ×1.2
  // возвращает схватку в коридор: без него зона стоила 12.6% валовой при
  // соседях по 14-16.
  //
  // ЗДЕСЬ ЖЕ ЕДИНСТВЕННЫЙ ПРОМАХ КОНТРАКТА ЦЕНЫ БОЯ: Изувер теряет на этой
  // полосе меньше коридора. Поднять полосу нельзя — попытка вернула Изувера
  // в коридор ценой Стража, улетевшего за верхний край: цена боя это
  // «входящий минус реген», и один и тот же множитель двигает классы
  // по-разному, потому что реген у них разный. Число полосы одно на обоих,
  // поэтому промах остаётся, и тест считает его поимённо, а не прячет
  // в широкий допуск.
  { belowLevel: 11, mult: new Decimal(0.9), damageMult: new Decimal(1.2) },
]
function earlyStep(level: number) {
  return EARLY_HP_DISCOUNT.find((step) => level < step.belowLevel)
}

// Множители уровня: у моба 1 уровня все равны 1 (до скидки ранних полос).
/**
 * УРОВЕНЬ МОБА ПРИ СПАВНЕ — ВОКРУГ УРОВНЯ ГЕРОЯ, а не равномерно по полосе.
 *
 * Раньше зона выдавала любой из пяти своих уровней с равной вероятностью, и
 * это ломало ровно то, ради чего полоса и заведена. Герой, только пришедший
 * в зону 21-25, в пятой части боёв дрался с двадцать пятым — на четыре
 * уровня старше себя; герой, доигравший её до двадцать пятого, в пятой части
 * боёв получал двадцать первого, который умирал с двух ударов. Отсюда и
 * записанный аудитом «дрейф темпа по зоне 46.8 %»: за пять уровней зоны
 * время убийства уходило с пятнадцати секунд до восьми. Вторая ночь записала,
 * что сузить его можно «только более узкими полосами зон» — вот эти полосы.
 *
 * РАСПРЕДЕЛЕНИЕ ЗАДАНО ДАННЫМИ, а не формулой в коде: 70 % ровно уровень
 * героя, по 10 % на ±1, по 5 % на ±2. Сумма — единица, и это проверяется
 * тестом: перекос в данных иначе прошёл бы молча.
 *
 * ГРАНИЦЫ ПОЛОСЫ СИЛЬНЕЕ РАСПРЕДЕЛЕНИЯ. В зоне 21-25 герой двадцать первого
 * уровня не встретит девятнадцатого: смещения, выпадающие за полосу,
 * отбрасываются, а оставшиеся веса нормируются. Герой выше полосы получает
 * мобов, прижатых к её верхней границе, — как и было.
 *
 * ЧТО ЭТО СДЕЛАЛО СО ШТРАФОМ ОПЫТА ЗА ОТСТАВАНИЕ (XP_GAP_PENALTY). Ничего
 * там, где важно, и кое-что там, где нет. Уровень, на котором отставшая зона
 * ПЕРЕСТАЁТ платить опыт, не сдвинулся ни в одной из двадцати зон: он и был,
 * и остался «верх полосы + 11», потому что прижатый к верхней границе моб —
 * это ровно тот случай, на который считалась ступень. А вот полная доля
 * держится на два уровня дольше (верх полосы + 1 → + 3): раньше среднее по
 * всей полосе размазывало ступени данных в ровный скат (1.0, 0.9, 0.8 …),
 * теперь видны сами ступени — 1.0 держится, потом падает до 0.5. Ступенчатой
 * таблице это ближе, чем скат, которого в данных никогда не было.
 */
export const SPAWN_LEVEL_SPREAD: ReadonlyArray<{ offset: number; weight: number }> = [
  { offset: -2, weight: 0.05 },
  { offset: -1, weight: 0.1 },
  { offset: 0, weight: 0.7 },
  { offset: 1, weight: 0.1 },
  { offset: 2, weight: 0.05 },
]

export function hpScale(level: number): Decimal {
  const base = MONSTER_GROWTH.hpPerLevel.times(level - 1).plus(1)
  const step = earlyStep(level)
  return step ? base.times(step.mult) : base
}

/** Множитель опыта: своя, более пологая ставка — см. xpPerLevel. */
export function xpScale(level: number): Decimal {
  return MONSTER_GROWTH.xpPerLevel.times(level - 1).plus(1)
}

export function damageScale(level: number): Decimal {
  const base = MONSTER_GROWTH.damagePerLevel.times(level - 1).plus(1)
  const step = earlyStep(level)
  return step ? base.times(step.damageMult) : base
}

export function rewardScale(level: number): Decimal {
  return MONSTER_GROWTH.rewardPerLevel.times(level - 1).plus(1)
}

// Готовый шаблон моба: база * роль * уровень, награды ещё и на множитель зоны.
export function buildMonster(
  archetype: MonsterArchetype,
  level: number,
  rewardMultiplier: Decimal,
): MonsterTemplate {
  const reward = rewardScale(level).times(rewardMultiplier)
  const { role } = archetype
  const damage = MONSTER_BASE.damage.times(role.damageMult).times(damageScale(level))
  return {
    id: archetype.id,
    name: archetype.name,
    level,
    maxHp: MONSTER_BASE.maxHp.times(role.hpMult).times(hpScale(level)),
    // ДОЛЯ, А НЕ ВСЁ ЧИСЛО: вторую забирает цена находки (ITEM_SELL_BASE в
    // data/loot.ts). Обе доли делят одно и то же MONSTER_BASE.goldReward,
    // поэтому общий кран золота от переноса не меняется.
    goldReward: MONSTER_BASE.goldReward
      .times(GOLD_SOURCE_SHARE.monsters)
      .times(role.goldMult)
      .times(reward),
    xpReward: MONSTER_BASE.xpReward
      .times(role.xpMult)
      .times(xpScale(level))
      .times(rewardMultiplier),
    // Диапазон урона: пока min = max — разброс придёт вместе со способностями.
    damageMin: damage,
    damageMax: damage,
    swingTime: role.swingTime,
  }
}
