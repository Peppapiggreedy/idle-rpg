// Весь разбросанный игровой баланс в одном месте. Технические константы
// (STEP_MS, лимит шагов за кадр) живут в game/loop.ts — это не баланс.
// Баланс конкретных сущностей — в monsters.ts / upgrades.ts / rarity.ts / loot.ts.
import { Decimal } from '../game/numbers'

// Безоружный герой: пока экипировки нет, скорость оружия берётся отсюда.
// weaponSpeed — секунд между ударами, МЕНЬШЕ = быстрее.
export const UNARMED = {
  weaponSpeed: new Decimal(2.0),
  // Диапазон урона голых кулаков: среднее 10 за удар.
  weaponDamageMin: new Decimal(8),
  weaponDamageMax: new Decimal(12),
}

// Нормализация вклада силы атаки в удар: attackPower * weaponSpeed / AP_NORMALIZATION.
// Делит вклад так, что 14 единиц силы атаки дают +1 урона в секунду при ЛЮБОЙ
// скорости оружия — поэтому медленное оружие не проигрывает быстрому автоматически.
export const AP_NORMALIZATION = new Decimal(14)

// Замороженная константа миграции сейва v2 -> v3: тогдашняя скорость удара,
// по которой урон в секунду переводился в урон за удар. НЕ следует за балансом —
// иначе старые сейвы начали бы мигрировать по-разному.
export const LEGACY_V3_SWING_TIME_S = 2.0

// Базовые значения всех стат Воина — ступень «base» конвейера статов.
// Всё в Decimal: конвейер считает единообразно, конверсию в number для
// вероятностей/секунд делает stats.ts на выходе.
export const BASE_STATS = {
  attackPower: new Decimal(70), // сила атаки: даёт 70 * 2.0 / 14 = 10 к среднему удару
  weaponDamageMin: UNARMED.weaponDamageMin, // нижняя граница урона оружия
  weaponDamageMax: UNARMED.weaponDamageMax, // верхняя граница урона оружия
  maxHp: new Decimal(100),
  maxMana: new Decimal(50),
  weaponSpeed: UNARMED.weaponSpeed, // секунд между ударами оружия (меньше = быстрее)
  haste: new Decimal(0), // ускорение в долях: 0.2 = +20% скорости (больше = быстрее)
  critChance: new Decimal(0.05), // вероятность крита
  critMultiplier: new Decimal(2), // множитель урона крита
  hpRegen: new Decimal(1), // hp в секунду В БОЮ (медленный)
  hpRegenOutOfCombat: new Decimal(10), // hp в секунду ВНЕ боя (быстрый)
  manaRegen: new Decimal(9), // маны в секунду (постоянный)
  damageReduction: new Decimal(0), // доля срезаемого входящего урона, 0..1
}
// Что даёт уровень персонажа, за каждый уровень СВЕРХ первого. Без этого
// живучесть героя не растёт вовсе (её дают только редкие шмотки), и зоны с
// мобами высокого уровня остаются непроходимыми при любой прокачке урона.
export const PER_LEVEL = {
  maxHp: new Decimal(14),
  hpRegen: new Decimal(0.8),
  maxMana: new Decimal(5),
  manaRegen: new Decimal(0.5),
}
// Кривая опыта: XP_CURVE_BASE * level^XP_CURVE_EXPONENT — сколько опыта стоит
// следующий уровень. Степень задаёт форму кривой (уровни замедляются, но не
// встают колом), база — общий темп прокачки. База подобрана прогоном баланса
// (game/__tests__/balance.test.ts): с ней десятый уровень с нуля берётся за
// 28 минут игрового времени у игрока, который переезжает по мере открытия зон,
// и за 46 минут у того, кто так и остался на стартовом лугу.
export const XP_CURVE_BASE = new Decimal(45)
export const XP_CURVE_EXPONENT = 1.5

// Глобальный кулдаун: после умения, которое его тратит, любое другое такое
// умение недоступно столько игровых миллисекунд. Автоатаку GCD не трогает.
export const GCD_MS = 1500
// Задержка реакции автокаста: столько игровых миллисекунд проходит с момента,
// когда умение стало доступно, до того, как автокаст его применит. Это первая
// из ДВУХ причин, почему авто слабее ручной игры (вторая — автокаст не
// придерживает кулдауны). Никаких других штрафов за авто нет.
export const AUTOCAST_DELAY_MS = 500
// Потолок отставания автокаста от ручной игры. Обе причины отставания
// (задержка реакции и перебой) считаются честно, но их сумма в редких случаях
// — переросшая экипировка в слабой зоне — переваливает за разумное. Потолок
// не добавляет штрафа, а СНИМАЕТ лишний: авто не может отстать сильнее.
export const AUTOCAST_MAX_LOSS = 0.2
// Коэффициент оффлайна поверх модели автокаста. Железное правило:
// оффлайн <= автокаст <= ручная игра. Оффлайн НИКОГДА не считается по
// идеальной игре — только по автокасту, и ещё с этой поправкой.
export const OFFLINE_EFFICIENCY = 0.9
// Достижения дают постоянные бонусы; какие именно — в data/dungeons.ts.
// Пауза перед первым боссом и между боссами цепочки, мс.
export const DUNGEON_STEP_DELAY_MS = 1500
// Таланты: первое очко даётся на этом уровне, дальше по одному за уровень.
export const TALENT_FIRST_LEVEL = 10
// Сброс талантов за золото. Цена растёт с каждым сбросом — переобуваться
// бесконечно дёшево нельзя, иначе выбор ветки ничего не значит.
export const TALENT_RESET_BASE_COST = new Decimal(500)
export const TALENT_RESET_COST_GROWTH = new Decimal(2.5)
// Пауза между смертью моба и появлением следующего, мс.
export const RESPAWN_DELAY_MS = 300

// Порог «быстрых убийств» для сцены, убийств в секунду. Выше него анимация
// смерти не проигрывается: вместо неё короткая вспышка.
//
// Это НЕ баланс — на награды и темп число не влияет вовсе. Оно здесь
// потому, что зависит от темпа боя: при отладочном ускорении, на сильном
// герое в слабой зоне и при возврате из оффлайна мобы умирают чаще, чем
// длится любая анимация смерти. Копить трупы и строить очередь анимаций
// нельзя — сцена превратится в кладбище и сожрёт память.
export const FAST_KILL_THRESHOLD_PER_SEC = 2

// Сколько одинаковых событий подряд лог показывает отдельными строками,
// прежде чем свернуть их в одну («12 ударов, 1.2K урона»). Ниже порога
// читать интереснее по одному; выше — лента превращается в мельтешение,
// в котором не видно ни лута, ни смерти.
export const LOG_AGGREGATE_THRESHOLD = 3

// Сколько строк держит лента лога. Это ПРЕДСТАВЛЕНИЕ, а не состояние игры:
// в самом состоянии живёт короткий хвост (COMBAT_LOG_SIZE), из которого
// лента набирает свою историю. Растить состояние ради показа нельзя —
// оно попало бы в golden и в сейв.
export const LOG_VIEW_SIZE = 50
// Число слотов инвентаря; при полном инвентаре лут не выпадает.
export const INVENTORY_SIZE = 12
// Потолок оплачиваемого оффлайн-прогресса, часов.
export const OFFLINE_CAP_HOURS = 8
// Шаг оффлайн-агрегата, минут. Оффлайн считается не одним куском, а шагами:
// герой за восемь часов набирает уровни, а уровень меняет живучесть, значит
// и темп фарма. Один снимок статов на все восемь часов врал бы на десятки %.
export const OFFLINE_CHUNK_MIN = 1
// Период автосохранения по игровому времени, секунд.
export const AUTOSAVE_INTERVAL_S = 15
// Таймер воскрешения после смерти героя, игровых миллисекунд.
export const REVIVE_DELAY_MS = 30_000

// Пороги вердикта по зоне: доля времени, которую герой в ней жив (uptime из
// estimateCombatRate). Ниже 'hopeless' герой не успевает добить даже одного моба.
export const ZONE_VERDICT_UPTIME = {
  safe: 1, // не умирает вовсе
  risky: 0.75, // умирает изредка, фарм окупается
  deadly: 0.25, // умирает часто, но что-то приносит
}
