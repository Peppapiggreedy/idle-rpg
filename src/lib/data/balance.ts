/**
 * ШТРАФ ОПЫТА ЗА ОТСТАВАНИЕ. Разрыв считается по уровню КОНКРЕТНОГО МОБА:
 * `gap = уровень героя − уровень моба`. Не по уровню зоны — зона накрывает
 * пять уровней мобов, и на её границе штраф врал бы: у соседних мобов одной
 * и той же зоны разрыв отличается на четыре.
 *
 * Ступени: первая, чей `maxGap` не меньше разрыва, и выигрывает. Отрицательный
 * разрыв (моб выше героя) попадает в первую ступень — за то, что герой лезет
 * наверх, опыт не режут.
 *
 * ШТРАФ БЬЁТ ТОЛЬКО ПО ОПЫТУ. Золото, материалы, травы и лут не трогаются
 * намеренно: отставшие зоны обязаны оставаться полезными для фарма
 * материалов низкого тира. Отрежь у них ещё и золото — и за низкими
 * ингредиентами станет некуда пойти.
 */
export const XP_GAP_PENALTY: ReadonlyArray<{ maxGap: number; share: number }> = [
  { maxGap: 5, share: 1 },
  { maxGap: 10, share: 0.5 },
  { maxGap: Number.POSITIVE_INFINITY, share: 0 },
]

/** Доля опыта за моба такого уровня. Разрыв = уровень героя − уровень моба. */
export function xpGapShare(heroLevel: number, monsterLevel: number): number {
  const gap = heroLevel - monsterLevel
  for (const step of XP_GAP_PENALTY) {
    if (gap <= step.maxGap) return step.share
  }
  return XP_GAP_PENALTY[XP_GAP_PENALTY.length - 1].share
}

/**
 * Сколько убийств стоит переход с уровня L на следующий. Между опорными
 * точками — линейная интерполяция, за краями — крайние значения.
 */
export function killsToNextLevel(level: number): number {
  const first = KILLS_PER_LEVEL[0]
  const last = KILLS_PER_LEVEL[KILLS_PER_LEVEL.length - 1]
  if (level <= first.level) return first.kills
  if (level >= last.level) return last.kills
  for (let i = 1; i < KILLS_PER_LEVEL.length; i += 1) {
    const hi = KILLS_PER_LEVEL[i]
    if (level > hi.level) continue
    const lo = KILLS_PER_LEVEL[i - 1]
    const span = hi.level - lo.level
    const t = span === 0 ? 0 : (level - lo.level) / span
    return lo.kills + (hi.kills - lo.kills) * t
  }
  return last.kills
}

