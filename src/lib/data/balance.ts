// Что даёт уровень персонажа, за каждый уровень СВЕРХ первого. Без этого
// живучесть героя не растёт вовсе (её дают только редкие шмотки), и зоны с
// мобами высокого уровня остаются непроходимыми при любой прокачке урона.
//
// hpRegen — про ВЫЖИВАНИЕ В ДЛИННОМ БОЮ, и растёт он вместе с уроном мобов
// намеренно. Запас HP — буфер: при отрицательном балансе он только оттягивает
// смерть, а решает её именно скорость восстановления. С контрактом темпа бой
// стал длиться не полторы секунды, а десять, и под удар герой попадает на
// порядок дольше — поэтому ставка регена поднята с 0.8 до 2 за уровень.
// Пара «урон мобов за уровень моба» и «реген за уровень героя» держит две
// разные вещи сразу: своя зона проходима, а дальняя по-прежнему убивает.
