/**
 * ШТРАФ ОПЫТА ЗА ОТСТАВАНИЕ. Разрыв считается по уровню КОНКРЕТНОГО МОБА:
 * `gap = уровень героя − уровень моба`. Не по уровню зоны — зона накрывает
 * пять уровней мобов, и на её границе штраф врал бы: у соседних мобов одной
 * и той же зоны разрыв отличается на четыре.
 *
 * Ступени: первая, чей `maxGap` не меньше разрыва, и выигрывает. Отрицательный
 * разрыв (моб выше героя) попадает в первую ступень — за то, что герой лезет
 * наверх, опыт не режут.
 *
 * ШТРАФ БЬЁТ ТОЛЬКО ПО ОПЫТУ. Золото, материалы, травы и лут не трогаются
 * намеренно: отставшие зоны обязаны оставаться полезными для фарма
 * материалов низкого тира. Отрежь у них ещё и золото — и за низкими
 * ингредиентами станет некуда пойти.
 */
export const XP_GAP_PENALTY: ReadonlyArray<{ maxGap: number; share: number }> = [
  { maxGap: 5, share: 1 },
  { maxGap: 10, share: 0.5 },
  { maxGap: Number.POSITIVE_INFINITY, share: 0 },
]

/** Доля опыта за моба такого уровня. Разрыв = уровень героя − уровень моба. */
export function xpGapShare(heroLevel: number, monsterLevel: number): number {
  const gap = heroLevel - monsterLevel
  for (const step of XP_GAP_PENALTY) {
    if (gap <= step.maxGap) return step.share
  }
  return XP_GAP_PENALTY[XP_GAP_PENALTY.length - 1].share
}

// ПРЕДЛОЖЕНИЕ, КОТОРОЕ ПОКА НЕ ПРИМЕНЕНО: частичный штраф ЗОЛОТА за
// отставание. Лежит здесь, рядом со штрафом опыта, потому что решать его
// придётся тут же.
//
// ЧТО ИЗМЕРЕНО. Герой двадцатого уровня на стартовом лугу зарабатывает 55 249
// золота в час против 52 153 в своей зоне — то есть 106%, СТАРТОВАЯ ЗОНА
// ПЛАТИТ БОЛЬШЕ СВОЕЙ. Дальше доля падает (61% на сороковом, 39% на
// шестидесятом, 16% на сотом), но провал приходится ровно на те уровни, где
// игрок только учится выбирать зону. Опыта отставшая зона не платит вовсе —
// его режет XP_GAP_PENALTY, — а золото не тронуто ничем.
//
// ОТКУДА ЭТО БЕРЁТСЯ. Не из наград: моб стартового луга платит герою
// двадцатого уровня вчетверо меньше, чем моб его полосы. Дело в ТЕМПЕ —
// на лугу герой кладёт с одного удара, и убийств в час у него втрое больше.
// Мелкая награда на утроенном темпе обгоняет крупную на обычном.
//
// ПОЧЕМУ ЭТО НЕ ЛЕЧИТСЯ НАКЛОНОМ НАГРАДЫ. Проверено арифметикой в
// game/__tests__/gold.test.ts: при закреплённом общем росте дохода ЛЮБОЕ
// выравнивание кривой (меньше линейной прибавки, больше экспоненты зоны)
// одновременно поднимает долю стартовой зоны. Ровный доход и закрытая дыра
// тянут наклон в противоположные стороны, и одним числом их не развести.
//
// ПРЕДЛОЖЕНИЕ. Ступени по тому же разрыву, что и у опыта, но с ПОЛОМ, а не
// в ноль: отставшие зоны обязаны остаться местом, где берут низкие материалы,
// — просто перестать быть местом, где богатеют.
//
//   gap <= 5  -> 1.0     своя полоса, платят полностью
//   gap <= 10 -> 0.7
//   gap <= 20 -> 0.45
//   дальше    -> 0.3     пол: материалы фармить по-прежнему стоит
//
// По замеру это переводит долю стартовой зоны на двадцатом уровне со 106%
// на 48%, а на сотом с 16% на 5%. Материалы, травы, реагенты и лут штраф НЕ
// трогает — только золото: иначе за низкими ингредиентами станет некуда
// пойти, и это отдельное правило, которое ломать нельзя.
//
// ЦЕНА РЕШЕНИЯ. Правило «штраф бьёт только по опыту» записано в CLAUDE.md, и
// это предложение его меняет. Поэтому оно и лежит предложением: числа готовы,
// решение за владельцем.

// ---------------------------------------------------------------------------
// Разрыв уровней в ДРУГУЮ сторону: моб выше героя
// ---------------------------------------------------------------------------
//
// ЗАЧЕМ ЭТО ВООБЩЕ ПОНАДОБИЛОСЬ. Замер показал, что герой не обгоняет зоны —
// он их ПЕРЕПРЫГИВАЕТ. Эталонный герой ТРИДЦАТОГО уровня выживал в последней
// зоне игры, где мобы 96-100: обгон в семьдесят уровней. И это не край
// таблицы, а её середина — обгон рос с +10 на пятом уровне до +70 на
// тридцатом и ниже нуля не опускался нигде. Правило «зона по уровню» держалось
// только на том, что глубоко фармить невыгодно, — но НЕ ЗАПРЕЩЕНО там ничем.
//
// ПОЧЕМУ ЭТО НЕ ЛЕЧИТСЯ СТАВКОЙ РОСТА УРОНА. Всё в игре растёт линейно, и это
// осознанное решение (см. MONSTER_GROWTH). У линейных функций ОТНОШЕНИЕ
// соседних зон не зависит от ставки и с уровнем стремится к единице: на
// тридцатом уровне мобы зоны L+5 бьют всего на 24% больше своих, а запас
// прочности героя — двукратный. Подними ставку впятеро — отношение останется
// тем же, а коридор темпа в СВОЕЙ зоне сломается. Отсечка нужна резкая, и
// линейной кривой её не даёт ни одно число.
//
// ПОЭТОМУ ШТРАФ ЗА РАЗРЫВ, ровно как у опыта, только в другую сторону: моб
// выше героя бьёт БОЛЬНЕЕ. Первые LEVEL_GAP_FREE уровней разрыва бесплатны —
// это ширина полосы зоны, и внутри своей зоны штрафа нет вообще ни у кого.
// Дальше каждый уровень разрыва добавляет свою долю, и глубина перестаёт
// быть вопросом терпения.
//
// БЬЁТ ТОЛЬКО ПО ВХОДЯЩЕМУ УРОНУ. Награды, лут и опыт не трогаются: лезть
// наверх по-прежнему выгодно тому, кто это переживёт, — просто теперь это
// надо ещё пережить.

/** Сколько уровней разрыва бесплатны. Ровно ширина полосы зоны. */
export const LEVEL_GAP_FREE = 5

/** Насколько больнее бьёт моб за каждый уровень разрыва сверх бесплатных. */
export const LEVEL_GAP_DAMAGE_PER_LEVEL = 0.3

/**
 * Множитель входящего урона за то, что моб выше героя.
 * Разрыв = уровень моба − уровень героя; отставший моб бьёт как обычно.
 */
export function levelGapDamageMult(heroLevel: number, monsterLevel: number): number {
  const gap = monsterLevel - heroLevel
  if (gap <= LEVEL_GAP_FREE) return 1
  return 1 + LEVEL_GAP_DAMAGE_PER_LEVEL * (gap - LEVEL_GAP_FREE)
}

/**
 * Сколько убийств стоит переход с уровня L на следующий. Между опорными
 * точками — линейная интерполяция, за краями — крайние значения.
 */
export function killsToNextLevel(level: number): number {
  const first = KILLS_PER_LEVEL[0]
  const last = KILLS_PER_LEVEL[KILLS_PER_LEVEL.length - 1]
  if (level <= first.level) return first.kills
  if (level >= last.level) return last.kills
  for (let i = 1; i < KILLS_PER_LEVEL.length; i += 1) {
    const hi = KILLS_PER_LEVEL[i]
    if (level > hi.level) continue
    const lo = KILLS_PER_LEVEL[i - 1]
    const span = hi.level - lo.level
    const t = span === 0 ? 0 : (level - lo.level) / span
    return lo.kills + (hi.kills - lo.kills) * t
  }
  return last.kills
}

