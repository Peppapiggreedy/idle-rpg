// Героический режим — МОДИФИКАТОР существующего данжа, а не второй набор
// данных.
//
// ПОЧЕМУ МОДИФИКАТОР. Восемь данжей и двадцать четыре босса уже выводятся из
// параметров (см. data/dungeons.ts). Скопировать их «в героическом варианте»
// значило бы завести вторую лестницу, которая начнёт расходиться с первой на
// первой же правке чисел: подвинули рост урона мобов — обычная цепочка
// починилась, героическая осталась старой, и заметить это можно только
// прогоном каждой. Поэтому героика — ОДНА запись: что она делает с числами
// обычной цепочки и какие способности добавляет боссам.
//
// Способность привязана к МЕСТУ в цепочке, а не к боссу поимённо: три ступени
// одинаковы во всех восьми данжах (CHAIN в dungeons.ts), значит и добавка к
// ним одна и та же. Первый босс проверяет, умеет ли герой играть без
// наложенных эффектов, второй — успевает ли он добивать, третий — умеет ли
// тратить ресурс метко. Это ПРОВЕРКИ РАЗНОГО, а не «бьёт сильнее трижды».
import type { IconName } from '../ui/icons/manifest'
import type { LootTier } from './dungeons'

/**
 * Что делает способность. Ровно как флаг таланта (data/talents.ts): вид
 * эффекта плюс payload с числами. Логика ветвится по `kind`, а идентификатора
 * босса или способности не знает вовсе.
 */
export type BossAbilityEffect =
  // Рассеивание: раз в intervalSec боя с босса слетают наложенные эффекты
  // (а если clearsQueue — то и умение, поставленное на следующий замах).
  // Отметки считаются от ВРЕМЕНИ БОЯ, как у ярости, поэтому своего таймера
  // в состоянии нет и в сейв ничего не добавляется.
  | { kind: 'dispel'; intervalSec: number; clearsQueue: boolean }
  // Ускорение на низком здоровье: пока HP босса ниже hpShare, его замах
  // делится на (1 + hasteBonus). Это ускорение в ДОЛЯХ — то же правило, что
  // и у героя: плоская правка времени замаха увела бы его в ноль.
  | { kind: 'frenzy-below-hp'; hpShare: number; hasteBonus: number }
  // Отдача за трату ресурса: каждая потраченная доля запаса стоит герою
  // hpSharePerResource его максимума HP. Считается ДОЛЯМИ запаса, а не
  // абсолютной тратой: у маны и ярости разные числа, а штраф обязан быть
  // одинаковым для обоих классов.
  | { kind: 'punish-resource'; hpSharePerResource: number }

export interface BossAbilityDef {
  id: string
  name: string
  /** Иконка. Тип выведен из реестра: опечатка — ошибка проверки типов. */
  icon: IconName
  effect: BossAbilityEffect
}

