/**
 * Героический режим одной записью. Всё, что героика делает с обычной
 * цепочкой, лежит здесь — и правится здесь же, сразу для всех восьми данжей.
 */
export interface HeroicSpec {
  /** Служебный id: у режима он один, но схема проверки требует id. */
  id: string
  name: string
  icon: IconName
  /** Уровень героя, с которого героика открыта. Один на все восемь. */
  unlockRequirement: number
  /** Во сколько раз босс крепче и злее своего обычного двойника. */
  hpMult: number
  damageMult: number
  /** Во сколько раз щедрее награда: золото и опыт разом. */
  rewardMult: number
  /** Доля, на которую сдвигается отметка ярости. Меньше единицы — раньше. */
  enrageShare: number
  /** Тир лут-пула героики. Свой и выше любого обычного. */
  lootTier: LootTier
  /** Дополнительные способности ПО МЕСТУ в цепочке: по одной на босса. */
  abilityIds: readonly string[]
  /** Постоянный бонус к опыту за первое прохождение. Свой, крупнее обычного. */
  clearXpBonus: number
}

