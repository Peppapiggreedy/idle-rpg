// МАСТЕРСТВО: РЕМЕСЛО РАЗВИВАЕТСЯ, А НЕ НАСТУПАЕТ.
//
// До этого файла профессия открывалась уровнем героя и больше ничем:
// `recipeUnlockLevel` брал максимум из уровня рецепта и порога профессии, и
// на этом развитие заканчивалось. Дорос — знаешь всё; не дорос — не знаешь
// ничего. Промежуточного состояния не было вовсе, а именно в нём ремесло и
// живёт.
//
// РАСТЁТ ТОЛЬКО КРАФТОМ. Не уровнем, не временем, не убийствами. Это
// единственный вход, и он же единственная причина, по которой мастерство
// вообще что-то значит: число, которое растёт само, ничего не измеряет.
//
// У РЕЦЕПТА СВОЙ ПОТОЛОК, И ОН ВЫВЕДЕН ИЗ ПОЛОСЫ. Пока мастерство ниже
// потолка рецепта — крафт даёт прибавку; выше — не даёт ничего. Без потолка
// выгоднее всего было бы молотить САМЫЙ ДЕШЁВЫЙ рецепт: пошлина у него
// меньше, а прибавка та же. Потолок делает ровно обратное — чтобы расти
// дальше, надо перейти к следующему тиру.
//
// ЦЕНА СТУПЕНИ МАЛЕНЬКАЯ НАМЕРЕННО. Пошлина крафта уже берёт долю часового
// дохода за каждое нажатие (`CRAFT_TOLL_HOURS`), то есть время игрока
// оплачено один раз. Гринд мастерства поверх пошлины оплатил бы его дважды,
// и ремесло превратилось бы в работу.
import type { ProfessionId } from './recipes'
import { bandDepth, bandForLevel, LEVEL_BANDS, type BandId } from './bands'

/** Потолок мастерства. Сто — потому что проценты читаются без объяснений. */
export const MASTERY_MAX = 100

/**
 * Сколько мастерства даёт один крафт «в свою силу».
 *
 * Два — это ПЯТЬ КРАФТОВ НА ПОЛОСУ (у полосы десять очков потолка) и
 * полсотни на всю игру. Столько же ступеней у лестницы предметов: ремесло
 * идёт с игроком в ногу, а не отстаёт от неё на десятки нажатий.
 */
export const MASTERY_PER_CRAFT = 2

/** Через сколько очков сменяется ступень. Пять ступеней на сотню. */
export const MASTERY_RANK_STEP = 20

/**
 * ПРОФЕССИИ С МАСТЕРСТВОМ — ДВЕ, И ЭТО РЕШЕНИЕ, А НЕ НЕДОДЕЛКА.
 *
 * Глубина ставится там, куда игрок будет возвращаться. Кулинария варит
 * четыре порции еды на всю игру, реликварий — восемь именных вещей по
 * реагентам подземелий; ни в той, ни в другой нет лестницы, вдоль которой
 * можно расти. Шкалы у них нет, и выглядеть недоделанными они не должны:
 * у них её и не было.
 */
export const MASTERY_PROFESSIONS: readonly ProfessionId[] = ['smithing', 'herbalism']

export function hasMastery(profession: ProfessionId): boolean {
  return MASTERY_PROFESSIONS.includes(profession)
}

/** Ступень мастерства: имя и с какого значения начинается. */
export interface MasteryRankDef {
  id: string
  name: string
  /** Нижняя граница включительно. */
  from: number
}

/**
 * ПЯТЬ СТУПЕНЕЙ ЧЕРЕЗ КАЖДЫЕ ДВАДЦАТЬ. Имена — ремесленные, без званий и
 * титулов: игрок растёт в умении, а не в должности.
 */
export const MASTERY_RANKS: readonly MasteryRankDef[] = [
  { id: 'novice', name: 'Новик', from: 0 },
  { id: 'helper', name: 'Подручный', from: 20 },
  { id: 'artisan', name: 'Ремесленник', from: 40 },
  { id: 'master', name: 'Мастер', from: 60 },
  { id: 'elder', name: 'Старший мастер', from: 80 },
]

/** Ступень по значению мастерства. Ниже нуля не бывает — берётся первая. */
export function masteryRank(value: number): MasteryRankDef {
  const safe = Number.isFinite(value) ? value : 0
  let found = MASTERY_RANKS[0]
  for (const rank of MASTERY_RANKS) if (safe >= rank.from) found = rank
  return found
}

/** Сколько очков до следующей ступени; на последней — null. */
export function pointsToNextRank(value: number): number | null {
  const safe = Number.isFinite(value) ? value : 0
  const next = MASTERY_RANKS.find((r) => r.from > safe)
  return next ? next.from - safe : null
}

/**
 * ПОТОЛОК МАСТЕРСТВА ДЛЯ ПОЛОСЫ, и он выведен, а не назначен.
 *
 * Полос десять, очков сто — значит каждая полоса стоит ровно десять очков, а
 * потолок полосы это её место в лестнице. Рецепт луга упирается в десять,
 * рецепт последней полосы — в сто. Отдельного поля у рецепта нет: оно
 * разъехалось бы с его же уровнем на первой правке.
 */
export function masteryCeilingForBand(band: BandId): number {
  return Math.round(((bandDepth(band) + 1) * MASTERY_MAX) / LEVEL_BANDS.length)
}

/** Потолок по уровню рецепта — та же лестница, вход с другой стороны. */
export function masteryCeilingForLevel(level: number): number {
  return masteryCeilingForBand(bandForLevel(level).id)
}

/**
 * Мастерство героя, ВЫВЕДЕННОЕ ИЗ УРОВНЯ. Нужно ровно одному месту —
 * миграции сейва: ветеран сотого уровня не должен обнаружить себя новиком
 * только потому, что счётчик завели сегодня. В живой игре мастерство так не
 * считается никогда.
 */
export function masteryFromLevel(level: number): number {
  return masteryCeilingForLevel(level)
}
