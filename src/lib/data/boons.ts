// СВОЙСТВО ЛЕГЕНДАРНОЙ СБОРКИ: вещь правит УМЕНИЕ, а не только числа героя.
//
// До этого файла легендарной вещи было нечем отличаться от редкой, кроме
// величины: те же статы, только больше. Три «реликтовых» уникума так и стояли
// в списке — сумма чисел на восьми героических реагентах, и ни одной причины
// планировать их заранее, кроме «побольше».
//
// СБОРКА — ЭТО НЕ БОЛЬШЕ, А ИНАЧЕ, и правило у неё жёсткое:
//
//     СВОЙСТВО ОПЛАЧЕНО СОБСТВЕННЫМИ СТАТАМИ ВЕЩИ. Сумма — НОЛЬ.
//
// Вещь со свойством отдаёт долю своих модификаторов (`statShare`) и на эти
// деньги покупает правку умения. Она не сильнее легендарки своего уровня — она
// ДРУГАЯ: меняет, чем герой играет, а не насколько он крепок. Держит это
// строка в бюджете силы (`POWER_BUDGET.assembly`), и коридор у неё вокруг
// единицы — единственная такая строка во всём бюджете, и причина названа там
// же.
//
// ВИД ЭФФЕКТА ВЗЯТ СУЩЕСТВУЮЩИЙ — тот же, которым правит умение талант
// (`kind: 'ability'`): вещь называет УМЕНИЕ, ПОЛЕ и ОПЕРАЦИЮ, а применяет их
// один общий конвейер `game/abilityTune.ts`. Второй механики «предмет правит
// умение» в игре нет и заводить её нельзя: список настраиваемых полей закрыт
// (`ABILITY_TUNABLE`), и вещь не может тронуть то, чего в нём нет.
//
// ПРЕДМЕТ НАЗЫВАЕТ ID, А НЕ КОПИРУЕТ ЧИСЛА — тот же довод, что у прока: так
// одно свойство нельзя описать дважды по-разному.
import type { AbilityTune } from './abilities'

export interface BoonDef {
  id: string
  /** Имя свойства: его читает игрок в карточке вещи. */
  name: string
  /** Какое умение правится. */
  abilityId: string
  /** Правки: поле и операция, как у таланта. */
  tune: AbilityTune[]
  /**
   * ДОЛЯ СТАТОВ, КОТОРОЙ ВЕЩЬ ПЛАТИТ. Ноль запрещён схемой: свойство даром —
   * это прибавка к бюджету силы, а не перераспределение внутри него.
   * Списывается на генерации, в той же точке, где числа округляются
   * (`craftedItem`), — карточка обязана показывать то, что считает бой.
   */
  statShare: number
}

/**
 * ОДНА СБОРКА НА ИГРУ, И ЭТО НЕ ЗАГОТОВКА ПОД ДЕСЯТЬ. Свойство сдвигает
 * ротацию, а ротация у класса одна; вторая сборка либо повторит первую
 * («лечение ещё больше»), либо потребует своей строки в бюджете. Появится
 * второй готовый класс — появится и его сборка.
 */
export const BOONS: BoonDef[] = [
  {
    id: 'eight-locks',
    name: 'Восемь затворов',
    // ОТКАТ, А НЕ УРОН И НЕ ЛЕЧЕНИЕ. Статы вещь и так даёт числами, и
    // свойство «плюс к урону» было бы теми же статами под другим именем.
    // Откат меняет РИТМ: тяжёлое умение возвращается на треть быстрее, и
    // сборка начинает вознаграждать игру от ротации, а не от автоатаки.
    //
    // ПЕРВЫМ ЗДЕСЬ СТОЯЛО ЛЕЧЕНИЕ (+40 % к «Заживлению ран»), и прибор его
    // НЕ УВИДЕЛ: замер дал ровно ×1.000. Причина в модели цикла — лечение
    // входит в неё через привалы (`healCycle`), а полностью одетый герой на
    // потолке теряет за бой меньше, чем зазор между порогом лечения и
    // порогом привала, и до лечения дело не доходит вовсе. Свойство, которое
    // ничем не измерить, оплачивать нечем: «нулевая сумма» тогда означала бы
    // просто потерю статов. Замер и разбор — в docs/CRAFT.md.
    abilityId: 'shattering-blow',
    tune: [{ field: 'cooldownSec', kind: 'multiplier', value: 0.7 }],
    // ПОСЧИТАНО, А НЕ НАЗНАЧЕНО, и вот арифметика. Одно свойство без скидки
    // даёт ×1.040 (замер прибором бюджета). Двенадцать процентов статов
    // ОДНОЙ вещи из семи стоят всего ×0.985 — доля вещи в комплекте мала,
    // — то есть двенадцатью процентами свойство не окупить: сумма легла бы
    // на ×1.021. Чтобы отдать ровно те же четыре процента, платить надо
    // втрое больше: 0.32. Сдвинешь силу свойства — пересчитывай долю, иначе
    // сумма перестанет быть нулевой.
    statShare: 0.32,
  },
]

export const BOON_BY_ID: Record<string, BoonDef> = Object.fromEntries(
  BOONS.map((b) => [b.id, b]),
)

/**
 * Правки одного умения от всех надетых свойств. Пусто — свойств нет или они
 * про другое умение; тогда `tuneAbility` вернёт БАЗОВЫЙ объект бит в бит.
 */
export function boonTunes(ids: readonly string[], abilityId: string): AbilityTune[] {
  const out: AbilityTune[] = []
  for (const id of ids) {
    const boon = BOON_BY_ID[id]
    if (!boon || boon.abilityId !== abilityId) continue
    out.push(...boon.tune)
  }
  return out
}
