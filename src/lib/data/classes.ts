// Классы героя — ДАННЫЕ. Ни одного «если класс такой-то» в логике: класс
// описан набором полей, и весь код читает эти поля, а не имя класса.
//
// ГЛАВНОЕ ПОЛЕ — ресурс. Мана и ярость ведут себя противоположно: мана
// начинается полной, копится сама и обнуляет накопление при трате; ярость
// начинается пустой, копится ОТ БОЯ и тает, когда бой кончился. Обе описаны
// ОДНИМИ И ТЕМИ ЖЕ числами: сколько даёт удар свой и чужой, сколько тает вне
// боя, есть ли пауза после траты. Обнули одни поля — получишь ману, обнули
// другие — ярость; ветки в коде для этого не нужно.
import type { IconName } from '../ui/icons/manifest'
import { Decimal } from '../game/numbers'
import type { TalentModifier, BranchId } from './talents'
import type { SlotId } from './slots'
import type { AttributeId } from './items'
import type { Rarity } from '../types'

export type ResourceKind = 'mana' | 'rage'

export interface ResourceDef {
  kind: ResourceKind
  /** Полный запас на старте (мана) или пустой (ярость). */
  startFull: boolean
  /**
   * Какую ДОЛЮ полного запаса даёт один удар — свой и чужой. У маны оба
   * нуля: она копится временем, а не боем.
   *
   * Именно удар, а не единица урона: урон растёт неограниченно, а цена
   * умения — фиксированное число, и доход, пропорциональный урону, к концу
   * игры сделал бы ресурс бесплатным.
   *
   * И именно ДОЛЯ запаса, а не абсолютное число: число ударов в секунду от
   * прокачки почти не меняется, а запас растёт с уровнем — как и реген у
   * маны. С абсолютным числом изувер к концу лестницы отставал бы от стража
   * вчетверо, и это было бы не «другой ритм», а «класс похуже».
   */
  perSwingDealt: Decimal
  perHitTaken: Decimal
  /**
   * Какая ДОЛЯ полного запаса тает в секунду ВНЕ боя (пауза респауна,
   * привал). У маны ноль: она не тает. У ярости — то, что делает её ресурсом
   * непрерывного боя, а не копилкой на потом.
   *
   * Именно доля, по той же причине, что и у дохода с удара: запас растёт
   * с интеллектом вещей, и плоская утечка на большом запасе превращалась бы
   * в ничто — глубокий изувер копил бы ярость впрок, а это уже не ярость.
   */
  decayShare: Decimal
  /**
   * НАЛИВАЕТ ЛИ ПРИВАЛ ЗАПАС ДО ПОЛНОГО. У маны да — привал и есть её окно
   * восстановления, и модель боя на это опирается (`RestRefill` в
   * rotation.ts). У ЯРОСТИ НЕТ, и это не мелочь: ярость приходит ТОЛЬКО из
   * боя, и налить её отдыхом значило бы выдать её за бездействие — ровно за
   * то, чему она противоположна.
   *
   * Поле отдельное, а не вывод из `startFull`: «с чего начинается игра» и
   * «что делает привал» — разные вопросы, и склеивать их одним флагом значит
   * получить неверный ответ на второй, как только появится третий вид
   * ресурса.
   */
  restRefill: boolean
}

export interface StartingItem {
  slot: SlotId
  /** Id шаблона из data/items.ts: оружие или щит. Броне шаблон не нужен. */
  templateId?: string
  kind: 'weapon' | 'shield' | 'armor'
  /** Главный атрибут стартовой брони: у дропа он случайный, здесь — данные. */
  attribute?: AttributeId
  /**
   * Тир стартовой вещи. ДАННЫЕ, а не выбор кода: раньше редкость стартового
   * комплекта была строкой в `game/state.ts`, и «во что одет герой на первой
   * минуте» нельзя было прочитать в данных класса вообще.
   */
  rarity: Rarity
}

/**
 * Готовность класса. ДАННЫЕ, а не список id в тестах: до альфы игра держит
 * контракты баланса на ОДНОМ классе, и какой это класс — обязано читаться
 * здесь, а не в `balance.test.ts`.
 *
 * - `ready` — основной класс: все контракты (темп, цена боя, убийств на
 *   уровень, полный путь, golden) считаются по нему и роняют прогон.
 * - `preview` — выбирается и играется, но нигде не заявляется как
 *   сбалансированный: его контракты идут некритичными (пишут в лог, а не
 *   падают), а на экране выбора стоит честная пометка.
 */
export type ClassStatus = 'ready' | 'preview'

export interface ClassDef {
  id: string
  name: string
  /** Готовность: см. `ClassStatus`. Хотя бы один класс обязан быть `ready`. */
  status: ClassStatus
  /** Иконка. Тип выведен из реестра: опечатка — ошибка проверки типов. */
  icon: IconName
  /** Одна строка о том, как в него играют. Показывается при выборе. */
  tagline: string
  resource: ResourceDef
  /**
   * ПОКОЛЕНИЕ ДЕРЕВА ТАЛАНТОВ: номер меняется, когда ветки класса ПЕРЕСОБРАНЫ.
   * Сейв, записанный при старом номере, получает бесплатный сброс — ранги
   * обнуляются, очки возвращаются сами (доступные — это «заработано минус
   * вложено»), счётчик платных сбросов не трогается.
   *
   * Правило проекта «пересобрал дерево — дай бесплатный сброс» до этого жило
   * в голове автора миграции: каждая перестройка требовала ПОМНИТЬ про сейвы
   * и писать в них ветку по классу. Теперь оно держится ДАННЫМИ и одной общей
   * проверкой на загрузке: забыть нельзя, а сброс достаётся ровно тому классу,
   * чьё дерево тронули, — и никому больше.
   */
  treeRevision: number
  /** Стартовые статы: модификаторы конвейера с source 'class:<id>'. */
  baseMods: TalentModifier[]
  /** Умения класса, в порядке кнопок. */
  abilityIds: string[]
  /** Ветки дерева талантов, доступные классу. */
  branchIds: BranchId[]
  startingEquipment: StartingItem[]
}

