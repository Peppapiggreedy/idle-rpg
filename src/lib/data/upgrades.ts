/**
 * ЧТО ДЕЛАТЬ С ЛИШНЕЙ НАХОДКОЙ — настройка игрока, а не свойство героя.
 *
 * «Лишнее» считает приоритет апгрейда (`data/upgrade.ts`): находка, не
 * лучшая ни по одной из выбранных осей. Дальше решает это положение:
 *
 *   'keep' — как было: всё падает в сумку, разбирает игрок;
 *   'sell' — лишнее сразу уходит в золото;
 *   'dust' — лишнее сразу уходит в пыль.
 *
 * ЖЕЛЕЗНОЕ ПРАВИЛО СУМКИ СИЛЬНЕЕ И ЗДЕСЬ: вещь, лучшая хоть по одной оси,
 * не продаётся и не распыляется ни при каком положении. Автоматика убирает
 * мусор, а не находки.
 */
export type LootPolicy = 'keep' | 'sell' | 'dust'

export const LOOT_POLICIES: readonly LootPolicy[] = ['keep', 'sell', 'dust']

