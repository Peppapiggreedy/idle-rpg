/**
 * Что даёт покупка. Ровно два вида, и оба про разбор добычи:
 *
 *   'bag'    — плюс места в сумке;
 *   'policy' — открывает положение переключателя «что делать с лишним».
 *
 * Эффект — ФЛАГ С PAYLOAD'ом, а не ветка по id: логика смотрит на `kind`,
 * а числа лежат рядом. Новая покупка — строка здесь, а не правка кода.
 */
export type GoldUpgradeEffect =
  | { kind: 'bag'; slots: number }
  | { kind: 'policy'; policy: 'sell' | 'dust' }

export interface GoldUpgradeDef {
  id: string
  name: string
  /** Одна строка о том, что изменится. Текст для игрока живёт в UI. */
  description: string
  icon: IconName
  /** Уровень героя, с которого покупка появляется на экране. */
  level: number
  /** Цена в ЧАСАХ дохода своего уровня. Умножается на goldPerHourAt(level). */
  costHours: number
  effect: GoldUpgradeEffect
}

