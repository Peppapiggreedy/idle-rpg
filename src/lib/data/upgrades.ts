// ЛЕСТНИЦА ПОКУПОК — на что герой тратит золото, кроме крафта.
//
// ЗАЧЕМ ОНА. Золото в игре копится с каждого убийства, а тратить его до сих
// пор было практически не на что: пошлина крафта, сброс талантов — и всё.
// Кран без слива даёт число, которое растёт и ничего не значит; ровно так же
// не значит ничего и «стало на три процента больше» в конце игры. Покупка —
// это РЕШЕНИЕ игрока, к которому он идёт несколько часов и которое видно
// сразу после нажатия.
//
// ЧТО ЗДЕСЬ НЕ ПРОДАЁТСЯ. Ни единицы силы: ни статов, ни урона, ни выносливости.
// Иначе золото стало бы второй лестницей прокачки рядом с уровнями и
// предметами, и бюджет силы пришлось бы делить ещё и с ним. Продаётся только
// УДОБСТВО РАЗБОРА — место в сумке и право не разбирать её руками.
//
// ЦЕНА — В ЧАСАХ ДОХОДА, а не числом. Тот же приём, что у пошлины крафта
// (CRAFT_TOLL_HOURS): число пришлось бы держать в двух местах — в цене и в
// кривой золота, — и они разъехались бы на первой правке баланса. Час дохода
// берётся там же, где его берёт крафт: `goldPerHourAt` по уровню ступени.
