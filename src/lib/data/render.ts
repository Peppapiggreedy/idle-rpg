// Бюджеты слоя представления.
//
// Это НЕ баланс: ни одно число отсюда не влияет на бой, награды или темп.
// Они живут в data по тому же правилу, что и баланс, — настраиваемые числа
// не должны быть закопаны в компонентах, — но лежат отдельным файлом,
// чтобы никто не искал здесь урон, а в balance.ts число всплывающих цифр.

/**
 * Сколько всплывающих чисел висит на экране ОДНОВРЕМЕННО.
 * Потолок нужен не ради красоты: при отладочном ускорении и возврате
 * из оффлайна событий приходит сотнями за кадр, и без него DOM растёт,
 * пока вкладка не встанет колом.
 */
export const FLOATER_LIMIT = 24

/** Сколько живёт одно всплывающее число, мс. */
export const FLOATER_LIFE_MS = 900

/**
 * Выше этого множителя скорости симуляции всплывающих чисел нет вовсе.
 * На ×10 они всё равно нечитаемы, а стоят дорого.
 */
export const FLOATER_MAX_SPEED = 1

/** Ширина, ниже которой машина считается мобильной (тот же брейкпоинт, что в CSS). */
export const MOBILE_BREAKPOINT = 720

// --- Двумерная сцена ---------------------------------------------------
//
// Весь бюджет движения — на удар, а не на покой: в покое бойцы стоят,
// а вот попадание, крит, умение, лечение и смерть обязаны читаться с
// одного взгляда. Длительности ниже уходят в CSS переменными и задают
// ключевые кадры; менять их здесь, а не в компоненте.

/** Вспышка на цели и сдвиг тела от обычного удара, мс. */
export const HIT_FLASH_MS = 220

/** Крит держится дольше: игрок должен отличить его до того, как прочтёт число. */
export const CRIT_FLASH_MS = 380

/** Выпад бьющего (кто сейчас ударил), мс. */
export const STRIKE_MS = 200

/** Кольцо лечения над героем, мс. */
export const HEAL_PULSE_MS = 520

/**
 * Затухание убитого моба, мс. Дольше задержки респауна быть не может:
 * новый моб выходит на площадку сразу после неё, а старый должен успеть уйти.
 */
export const DEATH_FADE_MS = 280

/**
 * Всплывающих чисел на телефоне меньше: экран уже, каждое стоит перекладку,
 * а читать двадцать цифр в стопке всё равно невозможно.
 */
export const FLOATER_LIMIT_MOBILE = 10
