// Потолок частоты кадров сцены.
//
// Сцена рисуется не чаще 30 кадров в секунду и намеренно: показывать в ней
// нечего, что требовало бы 60 — два меша и площадка, — а на слабой машине
// и в браузере телефона лишние кадры стоят батареи. Игровое время это
// не трогает вообще: симуляция идёт своим фиксированным шагом в game/loop.ts,
// сцена только рисует то, что уже посчитано.

/** Кадров в секунду, которые рисует сцена. */
export const SCENE_FPS = 30

export interface FrameGate {
  /**
   * Пора ли рисовать кадр в момент t (мс). Если да — время из аккумулятора
   * списывается, и следующий раз наступит не раньше чем через 1/fps секунды.
   */
  shouldRender(t: number): boolean
}

/**
 * Аккумулятор времени, а не «сравнить с последним кадром»: при частоте
 * кадров браузера, не кратной нашей, простое сравнение даёт то 30, то 20
 * кадров, а аккумулятор держит среднее ровно на потолке.
 */
export function createFrameGate(fps: number = SCENE_FPS): FrameGate {
  const minMs = fps > 0 && Number.isFinite(fps) ? 1000 / fps : 0
  let last: number | null = null
  let accumulator = 0

  return {
    shouldRender(t: number): boolean {
      if (minMs <= 0) return true
      if (last === null) {
        // Первый кадр рисуем сразу: ждать треть секунды с пустым холстом
        // на глазах у игрока незачем.
        last = t
        return true
      }
      accumulator += Math.max(0, t - last)
      last = t
      if (accumulator < minMs) return false
      // Долг не отыгрываем: пропущенные кадры невозможно «дорисовать»,
      // а копить их значит выдать пачку рывков после возврата во вкладку.
      accumulator = 0
      return true
    },
  }
}
