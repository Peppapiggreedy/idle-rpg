//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ РАДИ ТРЁХ СЛОВ. Потому что в игре это уже соврало:
// лестница открытий писала «Осталось 2 уровней» — правило стояло на одном
// сравнении с единицей, а русский требует трёх форм. Один раз написанное
// правило чинится один раз; переписанное по месту врёт по месту.
const KEEP = [2, 0, 1, 1, 1, 2] as const

/**
 * Форма слова по числу: `plural(2, 'уровень', 'уровня', 'уровней')`.
 * Одиннадцать-четырнадцать — исключение, и оно здесь есть: «11 уровней»,
 * а не «11 уровень».
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(Math.round(n))
  const forms = [one, few, many]
  if (abs % 100 > 4 && abs % 100 < 20) return many
  return forms[KEEP[Math.min(abs % 10, 5)]]
}

/** «уровень / уровня / уровней» — самая частая тройка в интерфейсе. */
export function levelWord(n: number): string {
  return plural(n, 'уровень', 'уровня', 'уровней')
}
