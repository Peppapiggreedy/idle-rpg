// КУДА СТАВИТЬ ВСПЛЫВАЮЩЕЕ ОКНО У КУРСОРА. Одна функция на всю игру.
//
// Окон таких два — сравнение находки в сумке и описание надетого на кукле, —
// и границы экрана они обязаны считать одинаково: иначе одно у правого края
// перевернётся, а второе уедет за экран. Формула простая и вся здесь.
//
// Размер окна приходит ИЗМЕРЕННЫМ, а не угаданным: и там, и там компонент
// читает свой `getBoundingClientRect` после отрисовки. Догадка о размере
// врёт ровно на тех вещах, у которых много модификаторов, — то есть на
// самых интересных.

/** Отступ от курсора: окно не должно лежать под ним самим. */
export const TIP_GAP = 14

export interface TipBox {
  w: number
  h: number
}

export interface TipViewport {
  width: number
  height: number
}

/**
 * Левый верхний угол окна. Не хватает места справа — открываемся слева, не
 * хватает снизу — выше курсора. К краю не прижимаемся вплотную: четыре
 * пикселя остаются, иначе окно выглядит обрезанным.
 */
export function placeTip(x: number, y: number, box: TipBox, view: TipViewport) {
  const left = x + TIP_GAP + box.w > view.width ? Math.max(4, x - TIP_GAP - box.w) : x + TIP_GAP
  const top = y + TIP_GAP + box.h > view.height ? Math.max(4, y - TIP_GAP - box.h) : y + TIP_GAP
  return { left, top }
}
