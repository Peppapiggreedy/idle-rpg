// ЭТАЖ ВЕТКИ — РЯД ТАЛАНТОВ, А НЕ ОДНА ЗАПИСЬ.
//
// Пока на этаже стоял один талант, «этаж» и «талант» были одним и тем же, и
// панель рисовала список. С альтернативами это разные вещи: у этажа ОБЩИЙ
// порог, а талантов на нём один, два или три — и порог подписан один раз на
// ряд, а не у каждой клетки.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ, А НЕ ФУНКЦИЕЙ ВНУТРИ КОМПОНЕНТА. Группировка —
// чистое преобразование данных, и проверять её надо на рядах из одного, двух
// и трёх талантов. Внутри `.svelte` такую проверку пришлось бы гонять
// браузером, то есть на том наполнении, которое сегодня лежит в данных;
// вынесенная функция проверяется на любом.
import { talentsInBranch, type BranchId, type TalentDef } from '../data/talents'

export interface TalentFloor {
  /** Номер этажа, считая сверху с единицы. */
  row: number
  /** Порог этажа: он ОДИН на весь ряд — это и есть определение этажа. */
  required: number
  /** Таланты ряда в порядке объявления в данных. */
  talents: TalentDef[]
}

/**
 * Разложить ветку по этажам.
 *
 * Порядок талантов внутри ряда — тот, в котором они лежат в данных: он и есть
 * порядок слева направо на экране, и решать его должен автор ветки, а не
 * сортировка по имени.
 */
export function floorsOf(branchId: BranchId): TalentFloor[] {
  return groupFloors(talentsInBranch(branchId))
}

/** То же по готовому списку — для проверок на выдуманных ветках. */
export function groupFloors(talents: TalentDef[]): TalentFloor[] {
  const rows = [...new Set(talents.map((t) => t.row))].sort((a, b) => a - b)
  return rows.map((row) => {
    const onRow = talents.filter((t) => t.row === row)
    return { row, required: onRow[0].requiredPointsInBranch, talents: onRow }
  })
}
