// Плоская прибавка к стату человеческим текстом.
//
// `formatNumber` — про золото, урон и опыт: он режет всё до целого и снабжает
// суффиксом разряда. Модификаторы конвейера так показывать нельзя: половина
// из них дробная (+0.05 множителя крита) и часть отрицательная (−0.5 секунды
// паузы восстановления). Через `formatNumber` талант «Свирепые удары» читался
// как «+0 множителя крита за ранг», а «Ясный ум» — как «+-0 паузы».
import { formatNumber, type Decimal } from '../game'

/** Порог, ниже которого число показываем как есть, а не разрядами. Всё, что
 *  мельче десятки, — это доли и секунды, и округлять их до целого нельзя. */
const SMALL = 10

/** Знак и число одной прибавки: «+3», «+0.05», «−0.5», «+1.20K». */
export function flatText(value: Decimal): string {
  const sign = value.sign() < 0 ? '−' : '+'
  const abs = value.abs()
  if (abs.gte(SMALL)) return `${sign}${formatNumber(abs)}`
  // Две цифры после запятой хватает всем нашим долям, а хвост из нулей
  // («+0.50») читается как обещание точности, которой в числе нет.
  return `${sign}${abs.toFixed(2).replace(/\.?0+$/, '')}`
}
