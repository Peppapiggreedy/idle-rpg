// Склонение имени класса. Это ТЕКСТ, поэтому живёт в ui: данные знают имя в
// именительном падеже, а «играть за кого» — вопрос языка.
//
// Пока классов было два, кнопка выбора клеила «а» к имени: «Стража»,
// «Изувера». Третий класс — «Псарь» — этим правилом превращался в «Псарьа».
// Правило одно и оно про форму слова, а не про класс: имя на мягкий знак
// меняет его на «я», остальные получают «а». Ветвления по id класса здесь
// нет — новый класс с любым именем склоняется сам.

/** Винительный падеж имени класса: «за Стража», «за Псаря». */
export function classAccusative(name: string): string {
  const trimmed = name.trim()
  if (trimmed.endsWith('ь')) return `${trimmed.slice(0, -1)}я`
  if (trimmed.endsWith('Ь')) return `${trimmed.slice(0, -1)}Я`
  return `${trimmed}а`
}
