// МЕМО ДЛЯ ДОРОГИХ ПРОИЗВОДНЫХ ОТ ИГРОВОГО СОСТОЯНИЯ.
//
// Стор `gameState` обновляется каждый тик — десять раз в секунду. Всё, что
// написано как `$derived(f($gameState))`, пересчитывается ровно так же часто,
// сколько бы оно ни стоило. А стоит оно иногда очень дорого:
//
//   • прогноз зон (`forecastAllZones`) гоняет `estimateCombatRate` по КАЖДОМУ
//     мобу КАЖДОЙ из двадцати зон — это под три сотни боевых оценок;
//   • оценка сумки считает `upgradeShare` на каждую вещь, а это две боевые
//     оценки на предмет: с полной сумкой ещё полсотни.
//
// Триста-четыреста прогонов боевой оценки в секунду съедают кадр целиком —
// и картинка начинает дёргаться ровно в тех разделах, где эти панели открыты.
// Перезагрузка «лечила» это потому, что активный раздел не сохраняется:
// игра открывалась на «Развитии», где ни той, ни другой панели нет.
//
// ПЕРЕСЧИТЫВАТЬ ИХ КАЖДЫЙ ТИК НЕ НУЖНО: входы у них — статы, экипировка,
// сумка, зона, — и за тик они не меняются. Ключ сравнивается ПО ССЫЛКАМ, а не
// глубоко, и этого достаточно: конвейер статов возвращает ТОТ ЖЕ объект, пока
// статы не помечены грязными (`ensureStats`), сумка — тот же массив, пока в
// ней ничего не произошло.
import type { GameState } from '../game'

/** Совпадают ли ключи: поэлементно и ПО ССЫЛКЕ. */
export function sameKey(a: readonly unknown[], b: readonly unknown[]): boolean {
  if (a.length !== b.length) return false
  for (let i = 0; i < a.length; i += 1) if (!Object.is(a[i], b[i])) return false
  return true
}

/**
 * Мемо на один вызов в компоненте. Держит ровно ОДНО последнее значение:
 * панель показывает одно состояние, история ей не нужна.
 */
export function createMemo<T>(): (key: readonly unknown[], compute: () => T) => T {
  let cached: { key: readonly unknown[]; value: T } | null = null
  return (key, compute) => {
    if (cached && sameKey(cached.key, key)) return cached.value
    const value = compute()
    cached = { key, value }
    return value
  }
}

/**
 * Ключ всего, от чего зависит БОЕВАЯ ОЦЕНКА: сила героя, во что он одет, что
 * лежит в сумке, где он стоит и что ему открыто.
 *
 * Текущий моб сюда НЕ входит намеренно: оценка предмета и прогноз зоны
 * считаются против медианного моба зоны, а не против того, кто стоит перед
 * героем сейчас (см. facingReference в game/equipment.ts). Не входят и
 * здоровье с маной: от них боевая оценка не зависит.
 *
 * Склянки входят ЧИСЛОМ, а не массивом: пока склянка действует, массив
 * пересоздаётся каждый тик (в нём тикает остаток), а на оценку влияет только
 * сам факт её действия — статы при этом уже пересчитаны конвейером.
 */
export function combatKey(s: GameState): readonly unknown[] {
  return [
    s.stats,
    s.equipment,
    s.inventory,
    s.level,
    s.talents,
    s.currentZoneId,
    s.unlockedZoneIds,
    s.dungeonsCleared,
    s.abilitySettings,
    s.activePotions.length,
  ]
}
