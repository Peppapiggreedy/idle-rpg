// Элементы с ЧИСЛАМИ СОСТОЯНИЯ, которые снимаются отдельно и без допуска.
//
// Полная страница сравнивается с долей 0.001 пикселей — иначе чужое
// сглаживание шрифта роняло бы каждый снимок. Но цифра в полоске здоровья —
// это сотые доли процента пикселей страницы, и смена «312 / 640» на
// «298 / 640» проходит сквозь такой порог незамеченной: два PR подряд
// подменили эталоны, а проверка молчала. Поэтому всё, что показывает число
// состояния, снимается ещё и своим кадром, где допуска нет вовсе.
//
// Новый числовой элемент — ОДНА СТРОКА ЗДЕСЬ; спека перебирает список сама
// и снимает каждый элемент на пресетах fresh и rich при 1280.
export interface NumericElement {
  /** Имя в названии снимка: numeric-<name>-<пресет>-1280.png. */
  name: string
  /** Локатор корня элемента. Svelte оставляет исходный класс рядом с хешем,
   *  поэтому класс из компонента годится как есть. */
  selector: string
  /** Подпись кнопки МЕНЮ, которое надо открыть, чтобы элемент появился;
   *  без неё элемент лежит в постоянной зоне и виден всегда. */
  menu?: string
}

export const NUMERIC_ELEMENTS: readonly NumericElement[] = [
  // Полоски героя (VitalsBar): здоровье, ресурс, опыт — «сколько / из скольких».
  { name: 'vitals', selector: '.vitals' },
  // Рама моба: имя, уровень, здоровье и урон в секунду. Снимки идут в режиме
  // ?scene=off, где на месте сцены стоит боевая панель (BattlePanel) — те же
  // числа, что несёт подпись сцены.
  { name: 'monster', selector: '.battle' },
  // Кошелёк в сумке (InventoryPanel): золото.
  { name: 'purse', selector: '.purse', menu: 'Сумка' },
]

