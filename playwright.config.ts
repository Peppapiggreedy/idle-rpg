import { defineConfig } from '@playwright/test'

// Визуальная регрессия: собираем игру, поднимаем vite preview и снимаем
// заранее заданные состояния. Эталоны лежат в tests/screenshots.
//
// Браузер не качается лишний раз: локально берётся уже установленная сборка
// из PLAYWRIGHT_BROWSERS_PATH, в CI — та же сборка из кеша (см. ci.yml).
// Версия @playwright/test закреплена ТОЧНО: она тянет ревизию Chromium 1194,
// ту же, что стоит в окружении. Разъедется версия — разъедется отрисовка,
// и эталоны начнут врать.
const PORT = 4173
const BASE = `http://127.0.0.1:${PORT}/idle-rpg/`

export default defineConfig({
  testDir: './tests',
  // Эталоны — плоским списком, а не деревом по имени теста: так их одинаково
  // удобно смотреть и в репозитории, и в скачанном артефакте.
  snapshotPathTemplate: 'tests/screenshots/{arg}{ext}',
  outputDir: 'test-results',
  forbidOnly: !!process.env.CI,
  retries: 0,
  // Снимки должны быть воспроизводимыми, а не быстрыми: один воркер снимает
  // борьбу за процессор, из-за которой страница успевает отрисоваться иначе.
  workers: 1,
  reporter: process.env.CI ? [['list'], ['html', { open: 'never' }]] : [['list']],
  expect: {
    toMatchSnapshot: {
      // Порог на канал гасит разницу в сглаживании шрифта; доля пикселей —
      // случайную рябь. Числа подобраны замером на живых поломках:
      //   смена отступа    -> меняется высота страницы, падает всегда;
      //   жирность 600→500 -> 2e-3…4e-3 различий, запас втрое;
      //   смена цвета      -> 7e-5…3e-4, СКВОЗЬ этот порог проходит.
      // Цвет тонкого текста занимает сотые доли процента пикселей страницы,
      // и порога, который ловил бы его и при этом переживал чужое сглаживание,
      // не существует. Поэтому палитру стережёт не картинка, а точный снимок
      // токенов — tests/tokens.spec.ts.
      threshold: 0.2,
      maxDiffPixelRatio: 0.001,
    },
  },
  use: {
    baseURL: BASE,
    browserName: 'chromium',
    viewport: { width: 1280, height: 900 },
    deviceScaleFactor: 1,
    // Анимации выключены на уровне системы: в app.css под этот запрос
    // замирают все переходы, иначе снимок ловил бы полкадра анимации.
    // В 1.56 reducedMotion живёт в contextOptions, а не в корне use.
    contextOptions: { reducedMotion: 'reduce' },
    colorScheme: 'dark',
    trace: 'off',
    video: 'off',
  },
  webServer: {
    // --host 127.0.0.1 обязателен: без него vite preview слушает `localhost`,
    // а на раннере GitHub это имя резолвится сначала в ::1. Playwright стучится
    // по 127.0.0.1 — и ждёт ответа до самого таймаута. Привязываем явно.
    command: `npm run build && npm run preview -- --host 127.0.0.1 --port ${PORT} --strictPort`,
    url: BASE,
    // Сервер поднимаем свой всегда. Переиспользование чужого экономит
    // секунду и стоит доверия к прогону: оставшийся с прошлого раза preview
    // отдаёт СТАРУЮ сборку, и тест молча сравнивает эталон сам с собой.
    reuseExistingServer: false,
    timeout: 180_000,
    // Вывод сервера показываем весь. Спрятанный stdout уже стоил одного
    // прогона вслепую: сборка и preview молчали три минуты, и в логе CI была
    // одна строка «timed out» без единой подсказки, что пошло не так.
    stdout: 'pipe',
    stderr: 'pipe',
  },
})
